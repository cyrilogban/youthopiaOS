export function usfmToDisplayReference(usfm: string): string {
  if (!usfm) return '';
  const parts = usfm.trim().split('.');
  if (parts.length >= 3) {
    const book = USFM_TO_BOOK[parts[0].toUpperCase()] || parts[0];
    const chapter = parts[1];
    const verse = parts.slice(2).join('.');
    return `${book} ${chapter}:${verse}`;
  }
  if (parts.length === 2) {
    const book = USFM_TO_BOOK[parts[0].toUpperCase()] || parts[0];
    return `${book} ${parts[1]}`;
  }
  return usfm;
}
